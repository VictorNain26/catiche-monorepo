/* The Rive scales (docs/charte.md): twelve steps per color, each at a target contrast with the
 * page background, light and dark, interpolated in OKLCH by Leonardo
 * (https://github.com/adobe/leonardo/tree/main/packages/contrast-colors). `bun scales.mjs` writes
 * scales.css, and scales.json for what reads no CSS (a manifest, the Open Graph image);
 * contrast.test.mjs checks both files match. The roles of theme.css point at the steps:
 * 1-2 backgrounds, 3-5 component fills, 6-8 borders, 9 non-text marks (3:1 and up), 10-11 text and
 * solids (4.5:1 and up), 12 the ink. */

import { writeFileSync } from 'node:fs';
import { BackgroundColor, Color, Theme } from '@adobe/leonardo-contrast-colors';

const RATIOS = [1, 1.08, 1.16, 1.26, 1.38, 1.6, 2, 2.6, 3.5, 5, 7.7, 14];

// The charte's colors, light then dark, as the keys each scale passes through.
const KEYS = {
  mist: ['#eef3f1', '#13252b'],
  water: ['#79cbc9', '#0e5361'],
  reed: ['#dce57a', '#4c5320'],
  fur: ['#e0a77e', '#8a4f2a'],
  green: ['#7fd49e', '#1b6e35'],
  red: ['#f4978e', '#b42318'],
  amber: ['#f3d27a'],
};

// The page background's lightness in each mode: the charte's brume and its dark counterpart.
const LIGHTNESS = { light: 96, dark: 10 };

function scale(lightness) {
  const named = (name) => Object.fromEntries(RATIOS.map((ratio, i) => [`${name}-${String(i + 1)}`, ratio]));
  const mist = new BackgroundColor({ name: 'mist', colorKeys: KEYS.mist, colorSpace: 'OKLCH', ratios: named('mist') });
  const colors = Object.entries(KEYS)
    .filter(([name]) => name !== 'mist')
    .map(([name, colorKeys]) => new Color({ name, colorKeys, colorSpace: 'OKLCH', ratios: named(name) }));
  // Hex: Leonardo 1.1.0 writes its OKLCH output as `oklch(1, 0, 16458%)`, no valid color.
  const theme = new Theme({ colors: [mist, ...colors], backgroundColor: mist, lightness, output: 'HEX' });
  return Object.entries(theme.contrastColorPairs).filter(([name]) => name !== 'background');
}

const block = (pairs, indent) => pairs.map(([name, value]) => `${indent}--${name}: ${value};`).join('\n');

export function scalesCss() {
  return `/* Generated by scales.mjs: do not edit, run \`bun scales.mjs\` in packages/tokens. */

:root {
${block(scale(LIGHTNESS.light), '  ')}
}

@media (prefers-color-scheme: dark) {
  :root {
${block(scale(LIGHTNESS.dark), '    ')}
  }
}
`;
}

export function scalesJson() {
  const values = (lightness) => Object.fromEntries(scale(lightness));
  return `${JSON.stringify({ light: values(LIGHTNESS.light), dark: values(LIGHTNESS.dark) }, null, 2)}\n`;
}

if (import.meta.main) {
  writeFileSync(new URL('./scales.css', import.meta.url), scalesCss());
  writeFileSync(new URL('./scales.json', import.meta.url), scalesJson());
}
